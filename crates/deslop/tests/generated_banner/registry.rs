/// Writes every case into `src`.
fn write_cases(src: &Path, cases: &[Case]) -> Result<()> {
    cases.iter().try_for_each(|case| {
        let source = format!("{}{SHARED_FUNCTION}{}", case.before, case.after);
        Ok(fs::write(src.join(case.file), source)?)
    })
}

/// Asserts every case's occurrence carries `hidden`.
fn assert_cases(report: &Value, cluster: &Value, cases: &[Case], hidden: bool) -> Result<()> {
    cases
        .iter()
        .try_for_each(|case| assert_visibility(report, cluster, case.file, hidden))
}

/// Reads one cluster-level count.
fn count(cluster: &Value, name: &str) -> Option<usize> {
    field(cluster, name)
        .as_u64()
        .and_then(|value| usize::try_from(value).ok())
}

#[test]
fn every_registered_banner_hides_its_file_and_a_near_miss_never_does() -> Result<()> {
    let (tmp, src) = temp_scan_dir(SCAN_DIR)?;
    write_cases(&src, &GENERATED)?;
    write_cases(&src, &HAND_WRITTEN)?;

    let (report, _body) = scan(tmp.path(), &src)?;
    let shown: Vec<&str> = HAND_WRITTEN.iter().map(|case| case.file).collect();
    let cluster = expect_cluster_spanning(&report, &shown)?;
    let everything = GENERATED.len().saturating_add(HAND_WRITTEN.len());
    assert_eq!(count(cluster, OCCURRENCES_TOTAL), Some(everything));
    assert_eq!(count(cluster, OCCURRENCE_COUNT), Some(HAND_WRITTEN.len()));
    assert_cases(&report, cluster, &GENERATED, true)?;
    assert_cases(&report, cluster, &HAND_WRITTEN, false)?;
    // One decision per file: the headline figure is exactly the lines the
    // shown occurrences cover, so rows and percentage cannot disagree.
    assert_eq!(
        metric_field(&report, DUPLICATED_LOC).as_u64(),
        Some(visible_duplicated_loc(&report)),
        "duplicated_loc must count the shown occurrences and nothing else: {report:#}"
    );
    Ok(())
}
