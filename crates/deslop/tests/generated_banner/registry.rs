//! [EXCLUSION-GENERATED-BANNER] Every registered banner hides its file,
//! and a near miss never does.
//!
//! One Dart corpus in which every file holds the same function, so the
//! report carries one cluster whose occurrences say, file by file, which
//! were hidden — and the per-file metrics say whether their lines counted.

use std::{fs, path::Path};

use anyhow::Result;
use serde_json::Value;

use super::{assert_visibility, scan};
use crate::common::{scan_dir::temp_scan_dir, *};

/// The scan root inside the temp workspace.
const SCAN_DIR: &str = "src";

/// The function every file of the corpus holds, copied verbatim.
const SHARED_FUNCTION: &str = "String describeBasket(int count) {\n  \
     final doubled = count * 2;\n  \
     final label = 'basket-$doubled';\n  \
     return label.toUpperCase();\n}\n";

/// Report fields the cluster-level counts are read from.
const OCCURRENCES_TOTAL: &str = "occurrences_total";
const OCCURRENCE_COUNT: &str = "occurrence_count";
const DUPLICATED_LOC: &str = "duplicated_loc";

/// One file of the corpus: `before`, the shared function, then `after`.
struct Case {
    /// File name, which also names the case in a failure message.
    file: &'static str,
    /// What the file opens with.
    before: &'static str,
    /// What follows the shared function.
    after: &'static str,
}

impl Case {
    /// A file that opens with `before`, then holds the shared function.
    const fn opening(file: &'static str, before: &'static str) -> Self {
        Self {
            file,
            before,
            after: "",
        }
    }

    /// A file that holds the shared function, then `after`.
    const fn closing(file: &'static str, after: &'static str) -> Self {
        Self {
            file,
            before: "",
            after,
        }
    }
}

