impl Language {
    /// `<stem>.<extension>`.
    fn file(&self, stem: &str) -> String {
        format!("{stem}.{}", self.extension)
    }

    /// Writes the hand-written pair and the generated copy into `src`.
    fn write(&self, src: &Path) -> Result<()> {
        let plain = format!("{}{}", self.prologue, self.function);
        for stem in HAND_WRITTEN_STEMS {
            fs::write(src.join(self.file(stem)), &plain)?;
        }
        let generated = format!("{}{}{}", self.prologue, self.banner, self.function);
        Ok(fs::write(src.join(self.file(GENERATED_STEM)), generated)?)
    }

    /// Asserts the language's cluster shows the hand-written pair and
    /// hides the generated copy, in the rows and in the percentage.
    fn assert_only_generated_is_hidden(&self, report: &Value) -> Result<()> {
        let shown: Vec<String> = HAND_WRITTEN_STEMS.map(|stem| self.file(stem)).to_vec();
        let names: Vec<&str> = shown.iter().map(String::as_str).collect();
        let cluster = expect_cluster_spanning(report, &names)?;
        for name in names {
            assert_visibility(report, cluster, name, false)?;
        }
        assert_visibility(report, cluster, &self.file(GENERATED_STEM), true)
    }
}

#[test]
fn a_banner_is_found_in_every_language_s_comment_syntax() -> Result<()> {
    let (tmp, src) = temp_scan_dir(SCAN_DIR)?;
    LANGUAGES
        .iter()
        .try_for_each(|language| language.write(&src))?;

    let (report, _body) = scan(tmp.path(), &src)?;
    LANGUAGES
        .iter()
        .try_for_each(|language| language.assert_only_generated_is_hidden(&report))
}

#[test]
fn a_banner_inside_a_docstring_is_a_string_not_a_comment() -> Result<()> {
    let (tmp, src) = temp_scan_dir(SCAN_DIR)?;
    let python = LANGUAGES
        .iter()
        .find(|language| language.extension == PYTHON_EXTENSION)
        .ok_or_else(|| anyhow!("the corpus has a Python corner"))?;
    python.write(&src)?;
    let docstring_file = python.file(DOCSTRING_STEM);
    let source = format!("{PYTHON_DOCSTRING_BANNER}{}", python.function);
    fs::write(src.join(&docstring_file), source)?;

    let (report, _body) = scan(tmp.path(), &src)?;
    python.assert_only_generated_is_hidden(&report)?;
    let cluster = expect_cluster_spanning(&report, &[docstring_file.as_str()])?;
    assert_visibility(&report, cluster, &docstring_file, false)
}
