//! [EXCLUSION-GENERATED-BANNER] Every language plugin says what a comment
//! is in its own grammar ([PIPELINE-LANG-TRAIT]), so a banner is found
//! whatever comment syntax carries it: `//`, `#`, `/* */`, a `/** */`
//! block with a ` * ` gutter, F#'s `(* *)`, under PHP's `<?php` tag,
//! behind a byte-order mark, and with Windows line endings.
//!
//! Each language gets two hand-written copies of one function and one
//! generated copy. The hand-written pair keeps the cluster in the report,
//! so the generated copy's occurrence is there to be read: hidden, with
//! none of its lines in the percentage.

use std::{fs, path::Path};

use anyhow::{anyhow, Result};
use serde_json::Value;

use super::{assert_visibility, scan};
use crate::common::{scan_dir::temp_scan_dir, *};

/// The scan root inside the temp workspace.
const SCAN_DIR: &str = "src";

/// File stems: two hand-written copies and the generator's output.
const HAND_WRITTEN_STEMS: [&str; 2] = ["plain_a", "plain_b"];
const GENERATED_STEM: &str = "generated";

/// A docstring is a string, not a comment, so a banner inside one never
/// counts — the file below is as visible as its hand-written siblings.
const DOCSTRING_STEM: &str = "docstring_only";
const PYTHON_EXTENSION: &str = "py";
const PYTHON_DOCSTRING_BANNER: &str =
    "\"\"\"Generated by the protocol buffer compiler.  DO NOT EDIT!\"\"\"\n\n";

/// One language's corner of the corpus.
struct Language {
    /// File extension, which also selects the plugin.
    extension: &'static str,
    /// What every file of the language opens with, before any comment.
    prologue: &'static str,
    /// The generator's banner in the language's own comment syntax.
    banner: &'static str,
    /// The function all three files hold, copied verbatim.
    function: &'static str,
}

