#!/usr/bin/env node
// [CORPUS-REGISTER-WORKSPACE] Builds the isolated workspace a clone judge works
// in. Run from this repository (the preparer role); hand the resulting directory
// to a judge who has never loaded this codebase. See the `clone-register-prepare`
// skill for the protocol, and `judge-clone-pairs` for what the judge then does.
//
// The workspace must be completely independent of this project: nothing in it
// may name the tool, reveal which engine produced which list, or expose the
// engine's own confidence in a pair. So this script copies the target source and
// nothing else, reduces both reports to a neutral `groups`/`regions` shape,
// assigns the A/B labels by a seeded coin flip recorded only in a key file that
// stays outside the workspace, and refuses to finish if its own output mentions
// this project by name.
//
// Candidates come from three places, and the judge can tell them apart from
// none of them. Two are the published pair lists. The third is `--nominations`:
// pairs proposed by readers who worked from the source alone and never saw a
// report. Without that third source a pass can only ever find pairs that WERE
// reported, so it can measure precision and is structurally blind to recall —
// a pair nothing reported would never become a candidate, and a false negative
// would be impossible to record. See [CORPUS-REGISTER-COVERAGE].
//
// What comes out is the whole of what a judge is given: the repository source,
// two pair lists, the drawn candidates, and the judging protocol installed at the
// root of the handed-over folder as a skill an agent can simply run. Nothing else
// travels with it, and the A/B key travels the other way — into --keys, which must
// sit outside the folder, because a key inside it is the answer sheet.
//
// Usage: register-workspace.mjs --workspace <dir> --source <dir>
//          --report-one <file> --report-two <file> --url <url> --sha <commit>
//          --keys <dir> [--seed <number>] [--nominations <file>]

import {
  cpSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

/// Candidates a judging pass is given. This is a ceiling, not a quota: past
/// roughly this many pairs a single repository stops paying for the time, and
/// the next hour is better spent on another repository or another language.
/// See docs/specs/corpus.md [CORPUS-REGISTER-COVERAGE]. Drawing fewer is fine.
const CANDIDATE_TARGET = 200;
/// Regions rendered per candidate; a judge compares two regions, not a family.
const REGIONS_PER_CANDIDATE = 2;
/// Prefix on a nominated pair's id, so it can never collide with a published
/// group id. It is used for sampling and then discarded — the id never reaches
/// the judge, who sees only a candidate number.
const NOMINATION_PREFIX = "n";
/// Upper line counts separating the size strata: one-liners, small, medium, large.
const SIZE_BANDS = [3, 10, 30];
/// Naming this project anywhere in the workspace would tell the judge what
/// produced the reports, which is contamination.
const FORBIDDEN_WORD = "deslop";
/// The judging protocol travels with the workspace so the judge never reaches
/// back into this repository to read it.
const JUDGING_SKILL = ".agents/skills/judge-clone-pairs/SKILL.md";
/// Where that protocol is installed in the handed-over folder, laid out exactly
/// as this repository lays out its own: the file lives under `.agents/`, and
/// `.claude/` symlinks to it so an agent opening the folder can run it by name.
/// One file, two names, no chance of the two drifting apart.
const SKILL_NAME = "judge-clone-pairs";
const AGENT_SKILLS = ".agents/skills";
const CLAUDE_SKILLS = ".claude/skills";
const SKILL_FILE = "SKILL.md";
const PROTOCOL_IN_ROOT = `${AGENT_SKILLS}/${SKILL_NAME}/${SKILL_FILE}`;
/// The same file, reached from inside one workspace.
const PROTOCOL_FROM_WORKSPACE = `../${PROTOCOL_IN_ROOT}`;
/// How `.claude/skills/<name>` reaches `.agents/skills/<name>` beside it.
const SKILLS_LINK = `../../${AGENT_SKILLS}/${SKILL_NAME}`;
/// Everything the judge reads that is not source, a report or a candidate is a
/// file in this repository, copied across unchanged. Nothing here is composed at
/// build time: prose generated by whoever happened to run the script is prose
/// nobody reviewed, and two runs a month apart would hand two different folders
/// to two judges. `root/` lands at the top of the folder, `workspace/` in every
/// repository directory.
const HANDOVER_DIR = ".agents/skills/judge-clone-pairs/handover";
const ROOT_HANDOVER = "root";
const WORKSPACE_HANDOVER = "workspace";
const GUIDE = "README.md";
/// Flags without which a workspace cannot be built honestly.
const REQUIRED_FLAGS = ["workspace", "source", "report-one", "report-two", "url", "sha", "keys"];
const USAGE =
  "usage: register-workspace.mjs --workspace <dir> --source <dir> --report-one <file> " +
  "--report-two <file> --url <url> --sha <commit> --keys <dir> [--seed <n>] [--nominations <file>]";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
const label = (region) => `${region.path}:${region.start_line}-${region.end_line}`;
const numbered = (index) => String(index + 1).padStart(4, "0");

const mulberry32 = (seed) => () => {
  seed |= 0;
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};

const shuffle = (items, random) => {
  for (let index = items.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(random() * (index + 1));
    [items[index], items[swap]] = [items[swap], items[index]];
  }
  return items;
};

/// A published pair list stripped to what a judge may see: which regions of the
/// source were grouped together. Rank, band, mass, node and occurrence counts,
/// thresholds, versions and timings are all the engine's opinion of itself.
const toGroups = (report) =>
  report.clusters
    .map((cluster) => ({
      id: cluster.id,
      regions: cluster.occurrences
        .filter((occurrence) => !occurrence.hidden)
        .map(({ path, start_line, end_line }) => ({ path, start_line, end_line })),
    }))
    .filter((group) => group.regions.length >= REGIONS_PER_CANDIDATE);

const sizeBand = (group) => {
  const longest = Math.max(...group.regions.map((r) => r.end_line - r.start_line + 1));
  const band = SIZE_BANDS.findIndex((limit) => longest <= limit);
  return band === -1 ? SIZE_BANDS.length : band;
};

/// Buckets every source across provenance and size, so the draw cannot end up
/// all one engine's findings, all one size of block, or all reported pairs.
/// Provenance drives the sampling and is then discarded — the judge never
/// learns it.
const stratify = (one, two, nominated) => {
  const idsOne = new Set(one.map((group) => group.id));
  const idsTwo = new Set(two.map((group) => group.id));
  const provenances = [
    one.filter((group) => !idsTwo.has(group.id)),
    two.filter((group) => !idsOne.has(group.id)),
    one.filter((group) => idsTwo.has(group.id)),
    nominated,
  ];
  return provenances.flatMap((groups) =>
    Array.from({ length: SIZE_BANDS.length + 1 }, (_, band) =>
      groups.filter((group) => sizeBand(group) === band),
    ),
  );
};

const draw = (strata, random) => {
  const drawn = new Map();
  while (drawn.size < CANDIDATE_TARGET && strata.some((stratum) => stratum.length > 0)) {
    for (const stratum of strata) {
      if (stratum.length === 0 || drawn.size >= CANDIDATE_TARGET) continue;
      const picked = stratum.splice(Math.floor(random() * stratum.length), 1)[0];
      drawn.set(picked.id, picked);
    }
  }
  return shuffle([...drawn.values()], random).map((group, index) => ({
    number: index + 1,
    regions: shuffle([...group.regions], random).slice(0, REGIONS_PER_CANDIDATE),
  }));
};

const renderRegion = (sourceDir, region) => {
  const text = readFileSync(join(sourceDir, region.path), "utf8").split("\n");
  const body = [];
  for (let line = region.start_line; line <= region.end_line; line += 1) {
    body.push(`${String(line).padStart(6)} | ${text[line - 1] ?? ""}`);
  }
  return [`### ${label(region)}`, "", "```", ...body, "```", ""].join("\n");
};

const renderCandidate = (sourceDir, candidate) =>
  [
    `# Candidate ${candidate.number}`,
    "",
    "Two regions of `source/`. Read both **in the files themselves**, diff them, then",
    "record CLEARLY IN, CLEARLY OUT or NOT CLEAR in `verdicts.json` with the diff you",
    "ran. If you hesitate, it is NOT CLEAR.",
    "",
    ...candidate.regions.map((region) => renderRegion(sourceDir, region)),
  ].join("\n");

const renderIndex = (candidates) =>
  [
    "# Candidates",
    "",
    `${candidates.length} pairs, shuffled. Work through them one at a time; each file`,
    "asks the same single question: **is this the same code written twice?**",
    "",
    ...candidates.map(
      (candidate) =>
        `- [ ] [${numbered(candidate.number - 1)}](${numbered(candidate.number - 1)}.md) — ` +
        candidate.regions.map((region) => `\`${label(region)}\``).join(" ↔ "),
    ),
    "",
  ].join("\n");

/// Installs the judging protocol at the root of the handed-over folder as a
/// skill, so an agent opening the folder can run it by name, and copies the
/// handover files across beside it. Idempotent: every workspace under one root
/// writes the same files, and each workspace links to this one copy of the
/// protocol rather than carrying its own. Everything here is a copy — nothing
/// is composed — so the same repository state always produces the same folder.
const installProtocol = (judgeRoot) => {
  const protocol = join(judgeRoot, PROTOCOL_IN_ROOT);
  mkdirSync(dirname(protocol), { recursive: true });
  cpSync(join(repoRoot, JUDGING_SKILL), protocol, { dereference: true });
  const linked = join(judgeRoot, CLAUDE_SKILLS, SKILL_NAME);
  mkdirSync(dirname(linked), { recursive: true });
  rmSync(linked, { force: true, recursive: true });
  symlinkSync(SKILLS_LINK, linked);
  const source = join(repoRoot, HANDOVER_DIR, ROOT_HANDOVER);
  cpSync(source, judgeRoot, { recursive: true, dereference: true });
  return [protocol, ...readdirSync(source).map((name) => join(judgeRoot, name))];
};

/// The key names which engine produced which list. Inside the folder it is the
/// answer sheet, so this refuses rather than trusting the caller to have chosen
/// a sensible path.
const keyPath = (keysDir, judgeRoot, workspace) => {
  const keys = resolve(keysDir);
  if (keys === judgeRoot || keys.startsWith(judgeRoot + sep)) {
    throw new Error(`--keys ${keys} is inside the folder handed to the judge (${judgeRoot})`);
  }
  mkdirSync(keys, { recursive: true });
  return join(keys, `${workspace.split(sep).pop()}.key.json`);
};

/// The workspace is worthless if it names its producer, so this is a hard stop
/// rather than a warning.
const assertNoLeak = (paths) => {
  const leaked = paths.filter((path) =>
    readFileSync(path, "utf8").toLowerCase().includes(FORBIDDEN_WORD),
  );
  if (leaked.length > 0) {
    throw new Error(`workspace names its producer in: ${leaked.join(", ")}`);
  }
};

const writeCandidates = (root, sourceDir, candidates) => {
  const folder = join(root, "candidates");
  rmSync(folder, { recursive: true, force: true });
  mkdirSync(folder, { recursive: true });
  const written = candidates.map((candidate) => {
    const path = join(folder, `${numbered(candidate.number - 1)}.md`);
    writeFileSync(path, renderCandidate(sourceDir, candidate));
    return path;
  });
  const index = join(folder, "index.md");
  writeFileSync(index, renderIndex(candidates));
  // The same pair list the candidate files render, in a shape the merge step
  // can read. Verdicts are keyed by candidate number and the ranges are taken
  // from here, so nothing depends on a judge re-typing a line number exactly.
  const pairs = join(folder, "pairs.json");
  writeFileSync(
    pairs,
    `${JSON.stringify(
      {
        pairs: candidates.map((candidate) => ({
          number: candidate.number,
          occurrences: candidate.regions.map(label),
        })),
      },
      null,
      2,
    )}\n`,
  );
  return [index, pairs, ...written];
};

/// Pairs proposed from the source alone, in the same neutral shape as a
/// published group. Absent is normal on a first pass; the file is written by
/// readers who have seen no report at all.
const readNominations = (path) => {
  if (!path) return [];
  return JSON.parse(readFileSync(path, "utf8"))
    .pairs.map((pair, index) => ({
      id: `${NOMINATION_PREFIX}${index}`,
      regions: pair.regions.map(({ path: file, start_line, end_line }) => ({
        path: file,
        start_line,
        end_line,
      })),
    }))
    .filter((group) => group.regions.length >= REGIONS_PER_CANDIDATE);
};

/// One `--flag value` pair per option, so nine arguments cannot silently shift
/// by one and hand a judge somebody else's source.
const parseFlags = (argv) => {
  const options = new Map();
  for (let index = 0; index < argv.length; index += 2) {
    const flag = argv[index];
    if (!flag.startsWith("--")) throw new Error(`expected a --flag, got '${flag}'\n${USAGE}`);
    options.set(flag.slice(2), argv[index + 1]);
  }
  const missing = REQUIRED_FLAGS.filter((name) => !options.get(name));
  if (missing.length > 0) throw new Error(`missing --${missing.join(", --")}\n${USAGE}`);
  return options;
};

const options = parseFlags(process.argv.slice(2));
const url = options.get("url");
const sha = options.get("sha");
const seed = Number(options.get("seed") ?? Date.now() % 1_000_000);
const random = mulberry32(seed);

const root = resolve(options.get("workspace"));
const judgeRoot = dirname(root);
const key = keyPath(options.get("keys"), judgeRoot, root);
mkdirSync(root, { recursive: true });
cpSync(resolve(options.get("source")), join(root, "source"), {
  recursive: true,
  filter: (path) => !path.includes("/.git"),
});
const rootFiles = installProtocol(judgeRoot);
const judging = join(root, "JUDGING.md");
rmSync(judging, { force: true });
symlinkSync(PROTOCOL_FROM_WORKSPACE, judging);

const reportOne = options.get("report-one");
const reportTwo = options.get("report-two");
const one = toGroups(readJson(reportOne));
const two = toGroups(readJson(reportTwo));
// The coin flip that decides which engine is called A, recorded outside the
// folder handed over so scoring can undo it and the judge cannot.
const flipped = random() < 0.5;
writeFileSync(join(root, "report-a.json"), JSON.stringify({ groups: flipped ? two : one }, null, 2));
writeFileSync(join(root, "report-b.json"), JSON.stringify({ groups: flipped ? one : two }, null, 2));
writeFileSync(
  key,
  JSON.stringify(
    {
      seed,
      "report-a": flipped ? reportTwo : reportOne,
      "report-b": flipped ? reportOne : reportTwo,
    },
    null,
    2,
  ),
);

const nominated = readNominations(options.get("nominations"));
const candidates = draw(stratify(one, two, nominated), random);
writeFileSync(join(root, "PINNED.txt"), `${url}\n${sha}\n`);
cpSync(join(repoRoot, HANDOVER_DIR, WORKSPACE_HANDOVER, GUIDE), join(root, GUIDE));
writeFileSync(
  join(root, "verdicts.json"),
  JSON.stringify({ clearly_in: [], clearly_out: [], not_clear: [] }, null, 2),
);
const candidateFiles = writeCandidates(root, join(root, "source"), candidates);
assertNoLeak([
  ...rootFiles,
  ...["report-a.json", "report-b.json", "PINNED.txt", GUIDE, "JUDGING.md", "verdicts.json"].map(
    (name) => join(root, name),
  ),
  ...candidateFiles,
]);

console.log(`workspace ready: ${root}`);
console.log(
  `  ${candidates.length} candidates drawn from ` +
    `${new Set([...one, ...two, ...nominated].map((group) => group.id)).size} available pairs ` +
    `(${nominated.length} proposed from the source alone) · seed ${seed}`,
);
console.log(`  protocol installed at ${join(judgeRoot, PROTOCOL_IN_ROOT)}`);
console.log("  no generated file names the producer");
console.log(`  key written to ${key} — outside the folder the judge is handed`);
console.log(`  hand ${judgeRoot} to a judge in a FRESH session, outside this repository`);
